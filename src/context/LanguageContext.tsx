export const getStoredLanguage = (): Language => {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = localStorage.getItem('testament_language');
    if (stored === 'en' || stored === 'es' || stored === 'fr') return stored;
    const browserLang = navigator.language.toLowerCase();
    if (browserLang.startsWith('es')) return 'es';
    if (browserLang.startsWith('fr')) return 'fr';
    return 'en';
  } catch {
    return 'en';
  }
};

export const setStoredLanguage = (lang: Language) => {
  try {
    localStorage.setItem('testament_language', lang);
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
    window.dispatchEvent(new CustomEvent('testament-language-changed', { detail: { language: lang } }));
  } catch {
    // ignore
  }
};

export const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  toggleLanguage: () => {},
  t: (key: string) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => getStoredLanguage());

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
    }
  }, [language]);

  useEffect(() => {
    const handleLangChange = (e: Event) => {
      const customEvent = e as CustomEvent<{ language: Language }>;
      if (customEvent.detail?.language) {
        setLanguageState(customEvent.detail.language);
      }
    };
    window.addEventListener('testament-language-changed', handleLangChange);
    return () => window.removeEventListener('testament-language-changed', handleLangChange);
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    setStoredLanguage(lang);
  };

  const toggleLanguage = () => {
    const next: Language = language === 'en' ? 'es' : language === 'es' ? 'fr' : 'en';
    setLanguage(next);
  };

  const t = useMemo(() => {
    return (key: string, params?: Record<string, string | number>): string => {
      const currentDict = translations[language] || translations.en;
      let text = currentDict[key] || translations.en[key] || key;
      if (params) {
        Object.entries(params).forEach(([paramKey, val]) => {
          text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
        });
      }
      return text;
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  return useContext(LanguageContext);
};
